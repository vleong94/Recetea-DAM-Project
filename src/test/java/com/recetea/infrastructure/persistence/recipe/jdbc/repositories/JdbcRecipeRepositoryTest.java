    @Test
    @DisplayName("findAllSummaries should include recipes without media (LEFT JOIN: null mainMediaStorageKey)")
    void findAllSummaries_ShouldIncludeRecipesWithoutMedia_WithNullStorageKey() {
        Recipe withMedia = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(1), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step A")));
        RecipeId idWithMedia = transactionManager.execute(() -> repository.save(withMedia));
        Recipe withMediaToUpdate = repository.findById(idWithMedia).orElseThrow()
                .addMedia(new RecipeMedia(null, idWithMedia, "media/img.jpg", "LOCAL", "image/jpeg", 1024L, true, 0));
        transactionManager.execute(() -> repository.update(withMediaToUpdate));

        Recipe noMedia = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(2), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step B")));
        RecipeId idNoMedia = transactionManager.execute(() -> repository.save(noMedia));

        List<RecipeSummaryResponse> summaries = repository.findAllSummaries(new PageRequest(0, 100)).content();

        RecipeSummaryResponse withMediaSummary = summaries.stream()
                .filter(s -> s.id().equals(idWithMedia)).findFirst().orElseThrow();
        RecipeSummaryResponse noMediaSummary = summaries.stream()
                .filter(s -> s.id().equals(idNoMedia)).findFirst().orElseThrow();

        assertEquals("media/img.jpg", withMediaSummary.mainMediaStorageKey(),
                "Recipe with image should expose its storage_key");
        assertNull(noMediaSummary.mainMediaStorageKey(),
                "Recipe without image should return null (LEFT JOIN produces no row)");
        assertEquals(2L, summaries.stream()
                .filter(s -> s.id().equals(idWithMedia) || s.id().equals(idNoMedia)).count(),
                "Both recipes should appear in the listing");
    }

    private BigDecimal queryQuantity(int recipeId, int ingredientId) {
        String sql = "SELECT quantity FROM recipe_ingredients WHERE recipe_id = " + recipeId + " AND ingredient_id = " + ingredientId;
        try (Connection conn = dataSource.getConnection();
             Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery(sql)) {
            return rs.next() ? rs.getBigDecimal("quantity") : null;
        } catch (SQLException e) {
            throw new RuntimeException(e);
        }
    }
