    @Test
    @DisplayName("findById should hydrate the aggregate's media list")
    void findById_ShouldHydrateMediaList() {
        Recipe recipe = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(1), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step 1")));
        RecipeId recipeId = transactionManager.execute(() -> repository.save(recipe));

        Recipe toUpdate = repository.findById(recipeId).orElseThrow()
                .addMedia(new RecipeMedia(null, recipeId, "key/main.jpg", "LOCAL", "image/jpeg", 204800L, true,  0))
                .addMedia(new RecipeMedia(null, recipeId, "key/extra.png", "LOCAL", "image/png",  102400L, false, 1));
        transactionManager.execute(() -> repository.update(toUpdate));

        Recipe loaded = repository.findById(recipeId).orElseThrow();

        assertEquals(2, loaded.getMediaItems().size(), "Should hydrate exactly 2 media items");
        RecipeMedia main = loaded.getMediaItems().stream().filter(RecipeMedia::isMain).findFirst().orElseThrow();
        RecipeMedia extra = loaded.getMediaItems().stream().filter(m -> !m.isMain()).findFirst().orElseThrow();

        assertEquals("key/main.jpg", main.storageKey());
        assertEquals("LOCAL", main.storageProvider());
        assertEquals("image/jpeg", main.mimeType());
        assertEquals(204800L, main.sizeBytes());
        assertEquals(0, main.sortOrder());

        assertEquals("key/extra.png", extra.storageKey());
        assertEquals(1, extra.sortOrder());
    }

    @Test
    @DisplayName("update should apply smart-diff: insert, update, and delete media items")
    void update_ShouldSmartDiffMedia() {
        Recipe recipe = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(1), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step 1")));
        RecipeId recipeId = transactionManager.execute(() -> repository.save(recipe));

        Recipe toUpdate = repository.findById(recipeId).orElseThrow()
                .addMedia(new RecipeMedia(null, recipeId, "key/a.jpg", "LOCAL", "image/jpeg", 100L, true,  0))
                .addMedia(new RecipeMedia(null, recipeId, "key/b.jpg", "LOCAL", "image/jpeg", 200L, false, 1));
        transactionManager.execute(() -> repository.update(toUpdate));

        Recipe afterFirst = repository.findById(recipeId).orElseThrow();
        assertEquals(2, afterFirst.getMediaItems().size());

        RecipeMediaId idA = afterFirst.getMediaItems().stream().filter(RecipeMedia::isMain).findFirst().orElseThrow().id();
        RecipeMediaId idB = afterFirst.getMediaItems().stream().filter(m -> !m.isMain()).findFirst().orElseThrow().id();

        // Swap main + add new item, remove A
        Recipe toPersist = afterFirst
                .setMainMedia(idB)
                .removeMedia(idA)
                .addMedia(new RecipeMedia(null, recipeId, "key/c.jpg", "LOCAL", "image/png", 300L, false, 2));
        transactionManager.execute(() -> repository.update(toPersist));

        Recipe final_ = repository.findById(recipeId).orElseThrow();

        assertEquals(2, final_.getMediaItems().size(), "Should have 2 items after diff");
        assertTrue(final_.getMediaItems().stream().anyMatch(m -> "key/b.jpg".equals(m.storageKey()) && m.isMain()),
                "key/b.jpg should now be main");
        assertTrue(final_.getMediaItems().stream().anyMatch(m -> "key/c.jpg".equals(m.storageKey())),
                "key/c.jpg should have been inserted");
        assertFalse(final_.getMediaItems().stream().anyMatch(m -> "key/a.jpg".equals(m.storageKey())),
                "key/a.jpg should have been deleted");
    }

