    @Test
    @DisplayName("update should persist the new rating + recomputed social metrics after addRating")
    void update_ShouldPersistMetrics_AfterAddRating() {
        Recipe recipe = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(1), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step 1")));
        RecipeId recipeId = transactionManager.execute(() -> repository.save(recipe));

        Recipe loaded = repository.findById(recipeId).orElseThrow()
                .addRating(new UserId(2), new Score(4), "Very good recipe");

        transactionManager.execute(() -> repository.update(loaded));

        BigDecimal persistedScore = queryBigDecimal(
                "SELECT average_score FROM recipes WHERE recipe_id = " + recipeId.value());
        int persistedTotal = queryCount(
                "SELECT total_ratings FROM recipes WHERE recipe_id = " + recipeId.value());
        int ratingRows = queryCount(
                "SELECT count(*) FROM ratings WHERE recipe_id = " + recipeId.value());

        assertEquals(0, new BigDecimal("4.00").compareTo(persistedScore),
                "average_score should be 4.00 (single vote of 4)");
        assertEquals(1, persistedTotal, "total_ratings should be 1");
        assertEquals(1, ratingRows, "Rating should have been inserted into the ratings table");
    }

    @Test
    @DisplayName("update should keep the ratings count stable when only metadata changes (idempotent upsert)")
    void update_ShouldNotChangeRatingCount_OnMetadataOnlyEdit() {
        Recipe recipe = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(1), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step 1")));
        RecipeId savedId = transactionManager.execute(() -> repository.save(recipe));

        seedRating(new UserId(2), savedId, 5);

        // Title-only edit. The repository's saveRatings call is unconditional but idempotent —
        // the ratings list rehydrated from the DB is upserted back unchanged, so the row count
        // stays at 1.
        Recipe loaded = repository.findById(savedId).orElseThrow().withTitle("Updated Title");
        transactionManager.execute(() -> repository.update(loaded));

        assertEquals(1, queryCount("SELECT count(*) FROM ratings WHERE recipe_id = " + savedId.value()),
                "Rating count should not change on metadata-only update");
    }

    @Test
    @DisplayName("findAllSummaries should read average_score and total_ratings from denormalized columns")
    void findAllSummaries_ShouldReadFromDenormalizedColumns() {
        Recipe recipeA = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(1), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step A")));
        RecipeId idA = transactionManager.execute(() -> repository.save(recipeA));
        // Push domain-computed metrics to the denormalized columns (simulates two ratings: avg 4.50)
        transactionManager.execute(() ->
                repository.updateSocialMetrics(idA, new BigDecimal("4.50"), 2));

        Recipe recipeB = buildRecipe()
                .syncIngredients(List.of(new RecipeIngredient(new IngredientId(2), new UnitId(1), BigDecimal.ONE)))
                .syncSteps(List.of(new RecipeStep(1, "Step B")));
        RecipeId idB = transactionManager.execute(() -> repository.save(recipeB));
        // recipeB has no ratings: denormalized defaults (0, 0.00) apply

        List<RecipeSummaryResponse> summaries = repository.findAllSummaries(new PageRequest(0, 100)).content();

        RecipeSummaryResponse summaryA = summaries.stream()
                .filter(s -> s.id().equals(idA)).findFirst().orElseThrow();
        RecipeSummaryResponse summaryB = summaries.stream()
                .filter(s -> s.id().equals(idB)).findFirst().orElseThrow();

        // Correctness is proven by the fact that seeding ratings directly into DB without calling
        // updateSocialMetrics leaves the denormalized columns unchanged — summaries read them directly.
        assertEquals(0, new BigDecimal("4.50").compareTo(summaryA.averageScore()),
                "average_score for recipe A should be 4.50 (read from denormalized column)");
        assertEquals(2, summaryA.totalRatings(),
                "total_ratings for recipe A should be 2 (read from denormalized column)");
        assertEquals(0, BigDecimal.ZERO.compareTo(summaryB.averageScore()),
                "average_score for recipe B should be 0.00 (no ratings, DEFAULT applied)");
        assertEquals(0, summaryB.totalRatings(),
                "total_ratings for recipe B should be 0");
    }

